CREATE TABLE IF NOT EXISTS espacios (
    id_espacio INT AUTO_INCREMENT PRIMARY KEY,
    numero_espacio INT NOT NULL UNIQUE,
    terreno VARCHAR(80) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'disponible',
    precio_mensual DECIMAL(10,2) DEFAULT 2500.00,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS apartados (
    id_apartado INT AUTO_INCREMENT PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_espacio INT NOT NULL,
    id_camion INT NULL,
    folio INT NULL UNIQUE,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'activo',
    motivo VARCHAR(200) NULL,
    precio_total DECIMAL(10,2) NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pagos (
    id_pago INT AUTO_INCREMENT PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_apartado INT NULL,
    monto DECIMAL(10,2) NOT NULL,
    concepto VARCHAR(100) NULL,
    metodo_pago VARCHAR(50) NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    fecha_pago DATE NULL,
    fecha_vencimiento DATE NULL,
    referencia VARCHAR(100) NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS accesos (
    id_acceso INT AUTO_INCREMENT PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_camion INT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    observaciones VARCHAR(255) NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

